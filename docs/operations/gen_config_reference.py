#!/usr/bin/env python3
"""Generates docs/operations/configuration.md from .env.example and docker-compose.yml.

    python3 docs/operations/gen_config_reference.py          # rewrite configuration.md
    python3 docs/operations/gen_config_reference.py --check  # exit 1 if configuration.md is stale

.env.example is the source of truth: every variable, its default and the comment block above it. docker-compose.yml
adds which services read each variable, plus the variables compose reads that .env.example does not list (resource
limits, replicas, images, ...) with their inline defaults.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENV_EXAMPLE = ROOT / ".env.example"
COMPOSE = ROOT / "docker-compose.yml"
OUTPUT = ROOT / "docs" / "operations" / "configuration.md"

VAR = re.compile(r"\$\{([A-Z_][A-Z0-9_]*)")
ASSIGN = re.compile(r"^(#\s*)?([A-Z_][A-Z0-9_]*)=(.*)$")


def parse_env_example():
    """[(section_text, [(name, default, note, commented_out)])] in file order."""
    sections, comments, current = [], [], None
    for raw in ENV_EXAMPLE.read_text().splitlines():
        line = raw.strip()
        match = ASSIGN.match(line)
        if match:
            commented, name, rest = match.groups()
            value, _, note = rest.partition("#")
            if current is not None and commented:
                note = (" ".join(comments) + " " + note).strip()
                comments = []
            if current is None or comments:
                current = (" ".join(comments), [])
                sections.append(current)
                comments = []
            current[1].append((name, value.strip(), note.strip(), bool(commented)))
        elif line.startswith("#"):
            comments.append(line.lstrip("#").strip())
        else:
            if comments and current is None:
                comments = []  # file header
            elif comments:
                comments = comments  # keep: belongs to the next block
    return sections


def default_of(text, start):
    """Default of the ${NAME...} starting at text[start] ('${'), honouring nested ${...}."""
    depth, i = 0, start
    while i < len(text):
        if text.startswith("${", i):
            depth += 1
            i += 2
            continue
        if text[i] == "}":
            depth -= 1
            if depth == 0:
                body = text[start + 2:i]
                m = re.match(r"[A-Z_][A-Z0-9_]*(:?-)(.*)$", body, re.S)
                return m.group(2) if m else None
        i += 1
    return None


def parse_compose():
    """{variable: (sorted services, first inline default)} for every ${VAR} in docker-compose.yml."""
    usage, defaults, section, service = {}, {}, None, None
    for raw in COMPOSE.read_text().splitlines():
        code = raw.split(" #", 1)[0] if not raw.lstrip().startswith("#") else ""
        if not code.strip():
            continue
        top = re.match(r"^([A-Za-z0-9_.-]+):", code)
        if top:
            section, service = top.group(1), None
        elif section == "services":
            svc = re.match(r"^  ([a-z0-9-]+):\s*$", code)
            if svc:
                service = svc.group(1)
        if section == "services" and service:
            owner = service
        elif section and section.startswith("x-"):
            owner = f"every service using {section}"
        elif section == "name":
            owner = "compose project name"
        else:
            owner = section
        for m in VAR.finditer(code):
            name = m.group(1)
            usage.setdefault(name, set()).add(owner)
            d = default_of(code, m.start())
            if d is not None and name not in defaults:
                defaults[name] = d
    return {k: (sorted(v), defaults.get(k)) for k, v in usage.items()}


def cell(text):
    return (text or "").replace("|", "\\|")


def render():
    sections = parse_env_example()
    compose = parse_compose()
    listed = {name for _, rows in sections for name, *_ in rows}
    out = [
        "# Configuration reference",
        "",
        "<!-- Generated by docs/operations/gen_config_reference.py from .env.example and docker-compose.yml. Do not edit by hand:",
        "     change .env.example (or docker-compose.yml) and rerun the script; --check fails CI when this file is stale. -->",
        "",
        "Compose reads these variables from the shell or from `.env` (`cp .env.example .env`). Every value shown is the",
        "default `docker-compose.yml` uses when the variable is unset, so an empty `.env` runs the local-development",
        "platform. Change every password and key outside local development. Ports are always published on 127.0.0.1 only.",
        "",
        "Services read their own settings as ASP.NET Core configuration (`Section__Key` environment variables, e.g.",
        "`Worker__DefaultRamMb`); compose maps the variables below onto them. Engine-hosting services also copy every",
        "`LEAN_<KEY>` variable onto LEAN's `Config` key `<key>` (lower-case, `_` -> `-`; e.g. `LEAN_DATA_FOLDER` ->",
        "`data-folder`), see `Services/QuantConnect.Services.Defaults/LeanConfigEnvironment.cs`. The Helm chart takes the",
        "same settings from `deploy/helm/lean-platform/values.yaml`.",
        "",
        "## Variables in `.env.example`",
        "",
    ]
    for text, rows in sections:
        heading = re.split(r"[.:(]", text, 1)[0].strip() or "General"
        out += [f"### {cell(heading)}", ""]
        if text.rstrip(".") != heading:
            out += [text, ""]
        out += ["| Variable | Default | Used by | Note |", "|---|---|---|---|"]
        for name, value, note, commented in rows:
            services = ", ".join(f"`{s}`" for s in compose.get(name, ([], None))[0]) or "compose / scripts"
            if commented:
                note = ("commented out in `.env.example`. " + note).strip()
            out.append(f"| `{name}` | `{cell(value)}` | {services} | {cell(note)} |" if value else f"| `{name}` | (empty) | {services} | {cell(note)} |")
        out.append("")
    extra = sorted(k for k in compose if k not in listed)
    out += [
        "## Other variables `docker-compose.yml` reads",
        "",
        "Not in `.env.example`; set them in `.env` or the shell to override the inline default (resource limits, replica",
        "counts, image pins, tuning). `LEAN_IMAGE_REGISTRY` / `LEAN_IMAGE_TAG` are set by `make` from `IMAGE_REGISTRY` /",
        "`IMAGE_TAG`.",
        "",
        "| Variable | Default | Used by |",
        "|---|---|---|",
    ]
    for name in extra:
        services, default = compose[name]
        shown = f"`{cell(default)}`" if default else "(empty)"
        out.append(f"| `{name}` | {shown} | {', '.join(f'`{s}`' for s in services)} |")
    out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run python3 docs/operations/gen_config_reference.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
